// Industry packs and type profiles seed (0B.03): config/packs/** → supabase/migrations/20261112110100_packs_profiles_seed.sql
//   node scripts/profiles/gen-seed.mjs           → validates the files against config/schemas and writes the migration
//   node scripts/profiles/gen-seed.mjs --check   → fails if a file is invalid or the migration differs (npm run check:profiles)
//   … --check --db                                → also validates every pack / profile row in the database ($DB_URL; CI)
// The files are version 1 of every pack and profile (the reviewed starting content). After this migration has run on
// staging / production, content changes are made in the panel as new versions (data, no release), not in these files.
import Ajv from 'ajv';
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../..', import.meta.url).pathname;
const OUT = join(ROOT, 'supabase/migrations/20261112110100_packs_profiles_seed.sql');
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));

/** Problems in the pack files (schema errors, unknown references between the files); empty = all good. */
export function problems() {
  const ajv = new Ajv({ allErrors: true, strict: false });
  const out = [];
  const packSchema = ajv.compile(read('config/schemas/industry-pack.schema.json'));
  const profileSchema = ajv.compile(read('config/schemas/type-profile.schema.json'));
  const { industries } = read('config/packs/industries.json');
  for (const industry of industries) {
    let pack;
    try {
      pack = read(`config/packs/${industry.key}/pack.json`);
    } catch {
      if (industry.signup_open) out.push(`${industry.key}: open for sign-up but has no pack`);
      continue;
    }
    if (!packSchema(pack)) for (const e of packSchema.errors) out.push(`${industry.key}/pack.json${e.instancePath}: ${e.message}`);
    const presets = new Set((pack.field_presets ?? []).map((f) => f.key));
    const modules = new Set((pack.modules ?? []).map((m) => m.key));
    for (const file of profileFiles(industry.key)) {
      const profile = read(`config/packs/${industry.key}/profiles/${file}`);
      if (!profileSchema(profile)) for (const e of profileSchema.errors) out.push(`${industry.key}/profiles/${file}${e.instancePath}: ${e.message}`);
      for (const f of profile.custom_fields ?? []) if (!presets.has(f)) out.push(`${industry.key}/profiles/${file}: custom field ${f} is not a preset`);
      for (const m of Object.keys(profile.modules ?? {})) if (!modules.has(m)) out.push(`${industry.key}/profiles/${file}: module ${m} is not in the pack`);
    }
  }
  return out;
}

function profileFiles(industry) {
  try {
    return readdirSync(join(ROOT, `config/packs/${industry}/profiles`)).filter((f) => f.endsWith('.json'));
  } catch {
    return [];
  }
}

const json = (value) => {
  const text = JSON.stringify(value);
  if (text.includes('$json$')) throw new Error('content contains the quote marker $json$');
  return `$json$${text}$json$::jsonb`;
};
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;

export function render() {
  const { industries } = read('config/packs/industries.json');
  // The order of profiles in the wizard follows Ch 7.4.
  const order = ['school', 'college', 'university', 'polytechnic', 'madrasa', 'english_medium', 'coaching', 'training', 'health'];
  const lines = [
    '-- GENERATED by scripts/profiles/gen-seed.mjs from config/packs and config/schemas — do not edit by hand.',
    '-- 0B.03 seed: the JSON schemas, the industry list (only education open, D20), the education pack and its nine type',
    '-- profiles as published version 1. The content is Proposed (Ch 7.10) until the owner approves it.',
    '',
    'insert into public.data_schemas (key, schema) values',
    `  ('industry_pack', ${json(read('config/schemas/industry-pack.schema.json'))}),`,
    `  ('type_profile', ${json(read('config/schemas/type-profile.schema.json'))})`,
    'on conflict (key) do update set schema = excluded.schema, updated_at = now();',
    '',
    'insert into public.industries (key, name, sort, signup_open) values',
    industries.map((i, n) => `  (${lit(i.key)}, ${json(i.name)}, ${(n + 1) * 10}, ${i.signup_open})`).join(',\n'),
    'on conflict (key) do nothing;',
  ];
  for (const industry of industries) {
    let pack;
    try {
      pack = read(`config/packs/${industry.key}/pack.json`);
    } catch {
      continue;
    }
    lines.push('', `insert into public.industry_packs (industry_key, version, payload, notes) values`,
      `  (${lit(industry.key)}, 1, ${json(pack)}, 'Initial content (Proposed, 0B.03)');`,
      `select app.pack_publish('pack', ${lit(industry.key)}, 1);`);
    const files = profileFiles(industry.key).map((f) => f.replace(/\.json$/, ''))
      .sort((a, b) => (order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99) || a.localeCompare(b));
    files.forEach((key, n) => {
      const profile = read(`config/packs/${industry.key}/profiles/${key}.json`);
      lines.push('', `insert into public.type_profiles (key, version, industry_key, payload, notes, sort) values`,
        `  (${lit(key)}, 1, ${lit(industry.key)}, ${json(profile)}, 'Initial content (Proposed, 0B.03)', ${(n + 1) * 10});`,
        `select app.pack_publish('profile', ${lit(key)}, 1);`);
    });
  }
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const found = problems();
  if (found.length) {
    console.error(found.map((p) => `PROFILES ${p}`).join('\n'));
    process.exit(1);
  }
  const text = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch { /* missing */ }
    if (current !== text) {
      console.error('PROFILES the seed migration differs from config/packs; run node scripts/profiles/gen-seed.mjs');
      process.exit(1);
    }
    console.log('profiles: pack files valid, seed migration up to date');
    if (process.argv.includes('--db')) {
      const sql = `select coalesce(string_agg(format('%s %s v%s: %s', kind, key, version, array_to_string(errors, '; ')), E'\\n'), '')
        from (select 'pack' as kind, industry_key as key, version, app.pack_payload_errors('pack', industry_key, payload) as errors from public.industry_packs
              union all
              select 'profile', key, version, app.pack_payload_errors('profile', industry_key, payload) from public.type_profiles) x
       where cardinality(errors) > 0`;
      const bad = execFileSync('psql', [process.env.DB_URL ?? 'postgresql://postgres:postgres@127.0.0.1:54322/postgres', '-X', '-A', '-t', '-c', sql],
        { encoding: 'utf8' }).trim();
      if (bad) {
        console.error(`PROFILES invalid rows in the database:\n${bad}`);
        process.exit(1);
      }
      console.log('profiles: every pack and profile row in the database is valid');
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.replace(ROOT, '')}`);
  }
}
